function sanitizeForSpeech(text){
 return text
  .replace(/[\u200D\uFE0E\uFE0F\u20E3\u{E0020}-\u{E007F}]/gu,"")
  .replace(/[\u{1F000}-\u{1FAFF}\u2600-\u27BF\u2B50\u2B55\u2190-\u2199\u21A9\u21AA]/gu," ")
  .replace(/\s+/g," ")
  .replace(/ +([,.;:!?])/g,"$1")
  .trim();
}
