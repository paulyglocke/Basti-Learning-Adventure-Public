package com.bellfamily.bastischool.learning.coloursort

import com.bellfamily.bastischool.learning.models.*
import com.bellfamily.bastischool.learning.progress.*
import com.bellfamily.bastischool.learning.session.*
import com.bellfamily.bastischool.learning.sorting.*
import org.junit.Assert.*
import org.junit.Test
import java.io.IOException
import java.security.MessageDigest
import java.util.Base64

/**
 * A fixed CSR1 checkpoint encoded from the pre-Phase-5A.1 v1 field contract.
 * ColourSort.kt, ColourSortHost.kt, Sorting.kt, SortingHost.kt and Sort models
 * are byte-for-byte unchanged from baseline c5fabdc67a4f2dbccaa8705f5a35ac4f46c70481.
 * The fixture is intentionally not generated by ColourSortHost in this test.
 */
class ColourSortHistoricalCompatibilityTest {
    private class Disk(var bytes: ByteArray) : ProgressStorage {
        override fun <T> access(block: (ProgressTransaction) -> T): T = block(object : ProgressTransaction {
            override fun read() = bytes.clone()
            override fun replace(bytes: ByteArray) { this@Disk.bytes = bytes.clone() }
        })
    }

    @Test fun historicalPartialRevisionOneJournalRestoresAndCompletesWithoutDuplicateEvents() {
        val fixture = Base64.getMimeDecoder().decode(
            requireNotNull(javaClass.getResourceAsStream("/com/bellfamily/bastischool/learning/coloursort/legacy-v1-partial-session.b64"))
                .bufferedReader().use { it.readText() }
        )
        assertEquals("27480e27c286f2d14229c8c8ec5b4cdf29da5c9b3e3311a9f9f7c547fa2eb233",
            MessageDigest.getInstance("SHA-256").digest(fixture).joinToString("") { "%02x".format(it) })

        val (historicalState, historicalPending) = ColourSortHost.decode(fixture)
        assertTrue(historicalPending.isEmpty())
        assertEquals(SessionId("legacy-sort-session-5a1b"), historicalState.id)
        assertEquals(ContentLanguage.ENGLISH, historicalState.language)
        assertEquals("rule.sort.colour", historicalState.rule.id.value)
        assertEquals(1, ColourSort.attempt(historicalState, 0).origin.activityRevision)
        assertEquals(ContentVersion(1, 1), ColourSort.attempt(historicalState, 0).origin.contentVersion)
        assertEquals(ColourSort.objects.map { it.id }, historicalState.order)
        assertEquals(listOf(true, false, false, false), historicalState.placements.map { it.placed })
        assertEquals(listOf(1, 0, 0, 0), historicalState.placements.map { it.attempts })
        assertEquals(ColourSort.red, historicalState.placements.first().lastCategory)

        val records = linkedMapOf<ProgressEventId, ProgressEvent>()
        val progress = object : ProgressRepository {
            override fun append(event: ProgressEvent): ProgressWriteResult {
                val old = records[event.id]
                if (old != null && old != event) return ProgressWriteResult.Failed(ProgressFailure.CONFLICT)
                records[event.id] = event
                return ProgressWriteResult.Saved(StoredProgressEvent(records.size.toLong(), 1L, event), old == null)
            }
            override fun read(query: ProgressQuery) = ProgressReadResult.Events(emptyList())
        }
        val firstAttempt = ColourSort.attempt(historicalState, 0)
        assertEquals(true, progress.append(firstAttempt) is ProgressWriteResult.Saved)
        val disk = Disk(fixture.clone())
        val restored = ColourSortHost(disk, progress)
        assertNull(restored.open(SessionId("ignored-new-session"), 123L, ContentLanguage.GERMAN))
        assertArrayEquals("A successful restore must keep the historical CSR1 checkpoint bytes", fixture, disk.bytes)
        assertEquals(historicalState.id, restored.state!!.id)
        assertEquals(historicalState.placements, restored.state!!.placements)
        assertEquals(1, records.values.filterIsInstance<AttemptEvent>().size)

        ColourSort.objects.drop(1).forEach { item ->
            restored.dispatch(SortAction.Select(item.id))
            val state = restored.state!!
            restored.dispatch(SortAction.Place(state.id, item.id, item.category, state.placement(item.id).attempts + 1))
        }
        assertTrue(restored.state!!.completed)
        assertTrue(restored.state!!.acknowledged)
        assertEquals(historicalState.id, restored.state!!.id)
        assertEquals(4, records.values.filterIsInstance<AttemptEvent>().size)
        assertEquals(1, records.values.filterIsInstance<CompletionEvent>().size)

        val finalBytes = disk.bytes.clone()
        val reopened = ColourSortHost(disk, progress)
        reopened.open(SessionId("ignored-again"), 5L, ContentLanguage.GERMAN)
        assertEquals(finalBytes.toList(), disk.bytes.toList())
        assertEquals(4, records.values.filterIsInstance<AttemptEvent>().size)
        assertEquals(1, records.values.filterIsInstance<CompletionEvent>().size)
        assertEquals(setOf(ColourSort.activity), records.values.map { it.origin.activity }.toSet())
    }
}
