#!/usr/bin/env python3
"""Generate native typed records and the retained web adapter from one authored catalogue."""
import argparse,json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
def quote(s): return json.dumps(s,ensure_ascii=False).replace('$','\\$')
def text(v): return 'ContentText.plain('+quote(v['en'])+', '+quote(v['de'])+')'
def ints(v): return 'listOf('+', '.join(map(str,v))+')'
def generate():
 d=json.loads((ROOT/'content/verbs.json').read_text())
 assert d['version']==1 and len(d['verbs'])==53 and len({v['id'] for v in d['verbs']})==53
 animals=d['animals']; assets=d['assets']
 for a in animals.values(): assert (ROOT/'app/src/main/assets'/a['path']).is_file(),a['path']
 header='// Generated by tools/generate_verbs.py from content/verbs.json. Do not edit.\n'
 kt=header+'package com.bellfamily.bastischool.learning.verbs\n\nimport com.bellfamily.bastischool.learning.models.*\n\ninternal object VerbRecords {\n    val animals = listOf(\n'
 for key,a in animals.items():
  semantic='crocodile' if key=='croc' else key
  kt+='        VerbAnimal(ContentId("animal.'+semantic+'"), '+quote(key)+', '+text(a)+', '+quote(a['path'])+'),\n'
 kt+='    ).associateBy { it.key }\n    val lessons = listOf(\n'
 for v in d['verbs']:
  m=v['motion'];a=assets[v['animal']];subject=animals[v['animal']]
  assert m['id']==v['id'] and m['animal']==v['animal']
  assert v['stages'] and len(v['stages'][0])==4
  assert all(x in animals for x in [v['animal']]+v['distractors'])
  assert len(set([v['animal']]+v['distractors']))==4
  assert all(0<=f<a['columns']*a['rows'] for f in m['frames']+m['still'])
  example=v['example']
  assert all(isinstance(example.get(language),str) and example[language].strip() for language in ('en','de'))
  stages=', '.join('LocalizedText('+quote(e)+', '+quote(g)+')' for e,g in zip(*v['stages']))
  kt+='        VerbLesson(ContentId('+quote(v['id'])+'), '+text(v['label'])+', '+text(v['explanation'])+', '+text(example)+',\n'
  kt+='            '+quote(v['animal'])+', listOf('+', '.join(quote(x) for x in v['distractors'])+'), VerbMotion('+quote(m['mode'])+', '+str(m['duration'])+', '+ints(m['frames'])+', '+ints(m['still'])+', '+quote(a['path'])+', '+str(a['columns'])+', '+str(a['rows'])+', animals.getValue('+quote(v['animal'])+').id),\n'
  kt+='            listOf('+stages+')),\n'
 kt+='    )\n}\n'
 legacy=header+'window.VerbCatalogue='+json.dumps(d,ensure_ascii=False,separators=(',',':'))+';\n'
 return {'app/src/main/java/com/bellfamily/bastischool/learning/verbs/VerbRecords.kt':kt,'app/src/main/assets/verb-catalogue.js':legacy}
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 for name,value in generate().items():
  path=ROOT/name
  if args.check: assert path.read_text()==value,'Regenerate '+name
  else: path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value)
